def fase_cristalina(entropia_inicial):
    # Torque 70/30: La proporción exacta para la coherencia cuántica
    logica_dura = entropia_inicial * 0.70
    sintropia_amabilidad = entropia_inicial * 0.30
    
    # Fractalidad: Normalizamos la salida para que sea siempre pura
    return (logica_dura - sintropia_amabilidad) / 10
